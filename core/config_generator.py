def _apn_for_mnc(mnc: str) -> str:
    return {"410": "broadband", "012": "vzwinternet", "480": "vzwinternet",
            "260": "fast.t-mobile.com"}.get(mnc, "internet")


def generate_user_db(sim: dict[str, Any]) -> str:
    """Generate user_db.csv for srsEPC HSS with this SIM subscriber.

    Format: name,auth_algo,imsi,k,op_type,op,amf,sqn,qci,ip_alloc
    srsRAN uses 'mil' for Milenage, not 'milenage'.
    """
    name = "ue1"
    return (
        "#\n"
        "# .csv to store UE's information in HSS\n"
        "# Kept in the following format: \"Name,Auth,IMSI,Key,OP_Type,OP/OPc,AMF,SQN,QCI,IP_alloc\"\n"
        "#\n"
        f"{name},mil,"
        f"{sim['imsi']},"
        f"{sim['ki'].lower()},"
        f"opc,"
        f"{sim['opc'].lower()},"
        f"{sim['amf']},"
        f"{sim['sqn']},"
        f"7,dynamic\n"
    )


def export_tower_configs(tower: dict[str, Any], output_dir: str) -> list[str]:
    """Write all 3 eNB config files for a tower to output_dir. Returns list of paths."""
    os.makedirs(output_dir, exist_ok=True)
    files = {
        "enb.conf": generate_enb_conf(tower),
        "rr.conf":  generate_rr_conf(tower),
        "sib.conf": generate_sib_conf(tower),
    }
    written = []
    for fname, content in files.items():
        path = os.path.join(output_dir, fname)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        written.append(path)
    return written


def export_ue_conf(sim: dict[str, Any], tower: dict[str, Any] | None,
                   output_dir: str) -> str:
    """Write ue.conf for a SIM profile to output_dir. Returns path."""
    os.makedirs(output_dir, exist_ok=True)
    content = generate_ue_conf(sim, tower)
    path = os.path.join(output_dir, "ue.conf")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    return path


