def generate_sim_for_tower(tower: dict[str, Any]) -> dict[str, Any]:
    """Auto-generate a SIM profile matched to a tower (same MCC/MNC/carrier)."""
    import uuid
    mcc = tower["mcc"]
    mnc = tower["mnc"]
    # IMSI = MCC + MNC + random 9 digits
    suffix = str(secrets.randbelow(10**9)).zfill(9)
    imsi = f"{mcc}{mnc}{suffix}"
    ki  = secrets.token_hex(16).upper()
    opc = secrets.token_hex(16).upper()
    apn_map = {"410": "broadband", "012": "vzwinternet", "480": "vzwinternet",
               "260": "fast.t-mobile.com"}
    apn = apn_map.get(mnc, "internet")
    return {
        "id":      f"SIM-{str(uuid.uuid4())[:8].upper()}",
        "name":    f"{tower['carrier']} — {tower['city']} ({tower['id']})",
        "carrier": tower["carrier"],
        "imsi":    imsi,
        "imei":    str(353490069000000 + secrets.randbelow(999999)),
        "ki":      ki,
        "opc":     opc,
        "amf":     "8000",
        "sqn":     "000000000001",
        "mcc":     mcc,
        "mnc":     mnc,
        "apn":     apn,
        "mode":    "soft",
        "_tower_id": tower["id"],
    }


